#include <stdio.h>
int main()
{
    int a = 10, b = 7;
   printf("My name is Raj Gupta and this is question 7\n");
    printf("a & b = %d\n", a & b); // Bitwise AND operator(&)
    printf("a | b = %d\n", a | b); // Bitwise OR operator(|)
    printf("a ^ b = %d\n", a ^ b); // Bitwise  XOR operator(^)
    printf("-a = %d\n", -a);       // Bitwise NOT operator(-)
    printf("a<< 1 = %d\n", a << 1);  // Bitwise Left shift operator(<<)
    printf("a>> 1 = %d\n", a >> 1);  // Bitwise Right shift operator(>>)

    return 0;
}
